#!/usr/bin/env python3
"""
Convert cookies from Go app format to Netscape format for yt-dlp
"""

import re
import sys
from datetime import datetime
from pathlib import Path


def parse_cookie_line(line):
    """Parse a single cookie line in format: NAME=<jargon>VALUE"""
    if not line.strip() or '=' not in line:
        return None
    
    # Split on first '=' to get name and rest
    parts = line.strip().split('=', 1)
    if len(parts) != 2:
        return None
    
    name = parts[0].strip()
    value_part = parts[1].strip()
    
    # Remove the jargon prefix - it appears as <...OjI or similar
    # Find where the actual cookie value starts (after the jargon)
    if '<' in value_part and 'OjI' in value_part:
        # Find the position after 'OjI' or similar marker
        idx = value_part.find('OjI')
        if idx != -1:
            # Skip past 'OjI' to get the actual value
            clean_value = value_part[idx + 3:]
        else:
            clean_value = value_part
    else:
        # No jargon found, use as-is
        clean_value = value_part
    
    # Remove trailing semicolon if present
    clean_value = clean_value.rstrip(';').strip()
    
    return name, clean_value


def create_netscape_cookie(name, value, domain=".youtube.com"):
    """
    Create a Netscape format cookie line
    Format: domain flag path secure expiration name value
    
    The flag indicates if the domain should be treated as a suffix match:
    - TRUE: domain is a suffix (starts with .)
    - FALSE: exact domain match only
    """
    # Set expiration far in the future (year 2030)
    expiration = int(datetime(2030, 1, 1).timestamp())
    
    # Flag must match whether domain starts with dot
    # If domain starts with '.', flag must be TRUE
    flag = 'TRUE' if domain.startswith('.') else 'FALSE'
    
    # Secure flag - TRUE for __Secure- and __Host- prefixed cookies
    secure = 'TRUE' if (name.startswith('__Secure-') or name.startswith('__Host-')) else 'FALSE'
    
    path = '/'
    
    return f"{domain}\t{flag}\t{path}\t{secure}\t{expiration}\t{name}\t{value}"


def convert_cookies(input_file, output_file):
    """Convert cookie file to Netscape format"""
    try:
        # Try different encodings
        content = None
        for encoding in ['utf-8', 'latin-1', 'iso-8859-1', 'cp1252']:
            try:
                with open(input_file, 'r', encoding=encoding, errors='ignore') as f:
                    content = f.read()
                break
            except UnicodeDecodeError:
                continue
        
        if content is None:
            # Last resort: read as binary and decode with errors ignored
            with open(input_file, 'rb') as f:
                content = f.read().decode('utf-8', errors='ignore')
        
        # Split by semicolons and newlines to get individual cookies
        cookie_lines = []
        for line in content.split(';'):
            line = line.strip()
            if line and '=' in line:
                cookie_lines.append(line)
        
        # Parse cookies
        cookies = {}
        for line in cookie_lines:
            result = parse_cookie_line(line)
            if result:
                name, value = result
                # Store unique cookies (last value wins for duplicates)
                cookies[name] = value
        
        if not cookies:
            print("Error: No valid cookies found in input file", file=sys.stderr)
            return False
        
        # Write Netscape format
        with open(output_file, 'w', encoding='utf-8') as f:
            # Netscape format header
            f.write("# Netscape HTTP Cookie File\n")
            f.write("# This file was generated by cookie converter\n")
            f.write("# This is a generated file! Do not edit.\n\n")
            
            # Write each cookie
            for name, value in cookies.items():
                netscape_line = create_netscape_cookie(name, value)
                f.write(netscape_line + '\n')
        
        print(f"✓ Successfully converted {len(cookies)} cookies")
        print(f"✓ Output written to: {output_file}")
        return True
        
    except FileNotFoundError:
        print(f"Error: Input file '{input_file}' not found", file=sys.stderr)
        return False
    except Exception as e:
        print(f"Error: {e}", file=sys.stderr)
        return False


def main():
    if len(sys.argv) < 2:
        print("Usage: python cookie_converter.py <input_cookie_file> [output_file]")
        print("\nExample:")
        print("  python cookie_converter.py cookies.txt")
        print("  python cookie_converter.py cookies.txt youtube_cookies.txt")
        sys.exit(1)
    
    input_file = sys.argv[1]
    
    # Default output filename
    if len(sys.argv) >= 3:
        output_file = sys.argv[2]
    else:
        input_path = Path(input_file)
        output_file = input_path.stem + '_netscape.txt'
    
    print(f"Converting cookies from: {input_file}")
    print(f"Output file: {output_file}\n")
    
    success = convert_cookies(input_file, output_file)
    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()